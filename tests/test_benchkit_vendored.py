"""Vendored benchkit infrastructure stays healthy inside this repo.

The hoist-and-vendor contract: these files are materialized copies from
benchmark-kit (see .benchkit.json). This repo must be able to verify them
OFFLINE, with no kit checkout present — that is what the drift gate in
scripts/relay_gates.py runs, and what these tests pin down."""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from check_vendored import check_consumer  # noqa: E402  (vendored)
from gates_kit import GateResult, GateSpec, evaluate_gates, render_gates_tex  # noqa: E402


def test_vendored_files_match_pinned_kit() -> None:
    report = check_consumer(ROOT)
    assert report.ok, report.summary()
    assert report.checked == 26  # +paper_tables.py (shared table formatters), benchkit@0.3.10


def test_manifest_targets_exist_and_headers_pin_one_version() -> None:
    manifest = json.loads((ROOT / ".benchkit.json").read_text())
    pinned = manifest["benchkit_version"]
    for entry in manifest["files"]:
        target = ROOT / entry["target"]
        assert target.exists(), f"vendored file missing: {entry['target']}"
        head = target.read_text().split("\n", 2)[:2]
        assert any(
            f"Vendored from benchkit@{pinned}" in line for line in head
        ), f"{entry['target']} missing/expired vendor header"


def test_vendored_client_keeps_house_pricing() -> None:
    """The models this repo's campaigns priced must stay at their published
    list prices (blindboard client table, verified against copybench)."""
    from blindboard.client import PRICES

    assert PRICES["gpt-5.4-nano"] == (0.20, 1.25)
    assert PRICES["gpt-5.4-mini"] == (0.75, 4.50)
    assert PRICES["gpt-5.6-luna"] == (1.0, 6.0)
    assert PRICES["gpt-5.6-terra"] == (2.5, 15.0)
    assert PRICES["gpt-5.6-sol"] == (5.0, 30.0)


def test_vendored_viz_keeps_validated_palette() -> None:
    """Figures were validated with these exact values; regeneration must
    stay byte-comparable."""
    from blindboard.viz import CATEGORICAL, GRID, SEQ_RAMP, SURFACE, TEXT, TEXT2, categorical_map

    assert (SURFACE, TEXT, TEXT2, GRID) == ("#fcfcfb", "#0b0b0b", "#52514e", "#e3e2de")
    assert categorical_map(
        ["gpt-5.4-nano", "gpt-5.6-luna", "gpt-5.6-terra", "gpt-5.6-sol"]
    ) == {
        "gpt-5.4-nano": "#2a78d6",
        "gpt-5.6-luna": "#1baf7a",
        "gpt-5.6-terra": "#eda100",
        "gpt-5.6-sol": "#008300",
    }
    assert len(SEQ_RAMP) == 13 and SEQ_RAMP[0] == "#cde2fb" and SEQ_RAMP[-1] == "#0d366b"
    assert CATEGORICAL[0] == SEQ_RAMP[7]  # ramp anchored on categorical blue


def test_vision_adapter_still_subclasses_shared_client() -> None:
    from blindboard.client import APIAdapter
    from relay.vision import VisionAdapter

    assert issubclass(VisionAdapter, APIAdapter)
    assert hasattr(VisionAdapter, "call_with_image")


def test_gates_tex_rendering_matches_house_format() -> None:
    results = evaluate_gates([GateSpec("demo", lambda: (True, "ok"))])
    tex = render_gates_tex(results, generator="scripts/relay_gates.py")
    assert tex.splitlines()[0] == "% Generated by scripts/relay_gates.py. Do not hand-edit."
    assert r"\begin{tabularx}{\linewidth}{llX}" in tex
    assert r"demo & PASS & ok \\" in tex
    assert isinstance(results[0], GateResult)
