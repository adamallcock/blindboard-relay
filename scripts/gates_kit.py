"""Release-readiness gates framework (obviousbench convention).

Every gate is CHECKED against artifacts at generation time, never
asserted. The consumer declares gates as python callables; the kit
evaluates them and renders the results as a generated LaTeX table (input
by the paper) and/or a markdown audit report.

Readiness profiles (obviousbench arxiv_readiness pattern): a gate may be
required only in some profiles (e.g. a human-baseline gate required for
"full" but optional for "preprint"). Under a profile that does not require
it, a failing gate is reported as WAIVED — visible, never hidden — and
does not block overall readiness; claims it would have supported must be
omitted or labeled as planned validation.

Declaration:

    from gates_kit import GateSpec, evaluate_gates, render_gates_tex

    def check_tests() -> tuple[bool, str]:
        ...
        return ok, "104 passed in 19.3s"

    SPECS = [
        GateSpec("test suite", check_tests),
        GateSpec("human baseline", check_baseline, profiles=("full",)),
    ]
    results = evaluate_gates(SPECS, profile="preprint")
    path.write_text(render_gates_tex(results, generator="scripts/my_gates.py"))
"""

from __future__ import annotations

from collections.abc import Callable, Iterable, Sequence
from dataclasses import dataclass

PROFILES = ("preprint", "full")


@dataclass(frozen=True)
class GateSpec:
    """A declared gate: check() -> (ok, summary). profiles=None means the
    gate is required under every profile; otherwise it is required only
    under the listed profiles (and WAIVED-not-blocking elsewhere)."""

    name: str
    check: Callable[[], tuple[bool, str]]
    profiles: tuple[str, ...] | None = None


@dataclass(frozen=True)
class GateResult:
    name: str
    ok: bool
    summary: str
    required: bool = True

    @property
    def status(self) -> str:
        if self.ok:
            return "PASS"
        return "FAIL" if self.required else "WAIVED"

    @property
    def blocking(self) -> bool:
        return self.required and not self.ok


def evaluate_gates(
    specs: Sequence[GateSpec], *, profile: str = "full"
) -> list[GateResult]:
    """Run every gate (a crashing check is a failing gate, with the
    exception text as its summary) and resolve required-ness against the
    active profile."""
    results: list[GateResult] = []
    for spec in specs:
        required = spec.profiles is None or profile in spec.profiles
        try:
            ok, summary = spec.check()
        except Exception as exc:  # noqa: BLE001 - a broken check must not pass silently
            ok, summary = False, f"gate check crashed: {type(exc).__name__}: {exc}"
        results.append(GateResult(spec.name, bool(ok), summary, required))
    return results


def all_pass(results: Iterable[GateResult]) -> bool:
    return not any(result.blocking for result in results)


def render_gates_tex(results: Sequence[GateResult], *, generator: str) -> str:
    """The generated gates table, exactly the relay_gates.tex shape:
    tabularx {llX}, PASS plain, FAIL red (WAIVED gray). Summaries are
    written verbatim — keep them TeX-safe at declaration time."""
    lines = [
        f"% Generated by {generator}. Do not hand-edit.",
        r"\begin{tabularx}{\linewidth}{llX}",
        r"\toprule",
        r"Gate & Status & Summary \\",
        r"\midrule",
    ]
    for result in results:
        if result.ok:
            status = "PASS"
        elif result.required:
            status = r"\textcolor{red}{FAIL}"
        else:
            status = r"\textcolor{gray}{WAIVED}"
        lines.append(f"{result.name} & {status} & {result.summary} \\\\")
    lines += [r"\bottomrule", r"\end{tabularx}"]
    return "\n".join(lines) + "\n"


def render_gates_markdown(
    results: Sequence[GateResult],
    *,
    title: str,
    generator: str,
    date: str = "",
) -> str:
    """Markdown audit report (obviousbench report shape: frontmatter,
    overall status, check table)."""
    ok = all_pass(results)
    lines = [
        "---",
        f"title: {title}",
        *( [f"date: {date}"] if date else [] ),
        "type: review",
        f"status: {'ready' if ok else 'blocked'}",
        "---",
        "",
        f"# {title}",
        "",
        f"Generated by {generator}. Do not hand-edit.",
        "",
        f"Overall status: {'PASS' if ok else 'BLOCKED'}",
        "",
        "| Gate | Status | Summary |",
        "| --- | --- | --- |",
    ]
    for result in results:
        summary = result.summary.replace("|", "\\|").replace("\n", " ").strip()
        lines.append(f"| {result.name} | {result.status} | {summary} |")
    lines.append("")
    return "\n".join(lines)


def print_gates(results: Sequence[GateResult]) -> None:
    for result in results:
        print(f"{result.status:6s} {result.name} — {result.summary}")
