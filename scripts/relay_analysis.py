def skeleton(note: str) -> str:
    return re.sub(r"[0-9]", "0", re.sub(r"[a-z]", "a", re.sub(r"[A-Z]", "A", note)))


def drift(cells):
    """Consecutive-baton schema-skeleton similarity (1.0 = stable format),
    with length diagnostics: mean skeleton length per cell, per-pair
    (similarity, length) records for the length-confound correlation, and
    early/late mean lengths in long runs (a rising trend on flat lengths
    is not a shortening artifact)."""
    out = {}
    pair_records = []  # (model, budget, base, similarity, mean pair length)
    for (model, cond, base, budget), seeds in cells.items():
        if cond != "freeform" or base not in ("std", "long"):
            continue
        sims, by_gen = [], defaultdict(list)
        lens, len_by_gen = [], defaultdict(list)
        for r in seeds.values():
            notes = [b for b in r.get("_batons", []) if b]
            for i, b in enumerate(notes):
                lens.append(len(skeleton(b)))
                len_by_gen[i].append(len(skeleton(b)))
            for i in range(1, len(notes)):
                a, b = skeleton(notes[i - 1]), skeleton(notes[i])
                sim = SequenceMatcher(None, a, b).ratio()
                sims.append(sim)
                by_gen[i].append(sim)
                pair_records.append((model, budget, base, sim, (len(a) + len(b)) / 2))
        if sims:
            def gen_mean(pred, table):
                vals = [v for g, vs in table.items() if pred(g) for v in vs]
                return sum(vals) / len(vals) if vals else None
            late_e = gen_mean(lambda g: g >= 12, by_gen) if base == "long" else None
            early_e = gen_mean(lambda g: g <= 6, by_gen) if base == "long" else None
            out[(model, base, budget)] = {
                "mean_sim": sum(sims) / len(sims),
                "n_pairs": len(sims),
                "mean_skeleton_len": sum(lens) / len(lens),
                "late_minus_early": (late_e - early_e)
                if late_e is not None and early_e is not None else None,
                "len_early": gen_mean(lambda g: g <= 6, len_by_gen) if base == "long" else None,
                "len_late": gen_mean(lambda g: g >= 12, len_by_gen) if base == "long" else None,
            }
    return out, pair_records


def seed_stability(cell: dict) -> dict:
    """Per-seed mean consecutive-baton skeleton similarity."""
    out = {}
    for s, r in cell.items():
        notes = [b for b in r.get("_batons", []) if b]
        sims = [SequenceMatcher(None, skeleton(notes[i - 1]), skeleton(notes[i])).ratio()
                for i in range(1, len(notes))]
        if sims:
            out[s] = sum(sims) / len(sims)
    return out


def drift_sensitivity(cells):
    """Versioned sensitivity; historical drift() remains unchanged.

    First disable autojunk on exactly the historical nonempty note pairs.
    Then use adjacent actual turns, omit the terminal note, and aggregate
    per episode. Early successor-note turns are 2--7, late turns 13 onward.
    Intervals describe episode means; pairs are not independent replicates.
    """
    out = {}
    for (model, cond, base, budget), seeds in cells.items():
        if cond != "freeform" or base not in ("std", "long"):
            continue
        same_pairs, changes, episode_means, trends = [], 0, [], []
        actual_pairs = 0
        for r in seeds.values():
            notes = [skeleton(b) for b in r.get("_batons", []) if b]
            for a, b in zip(notes, notes[1:]):
                clean = SequenceMatcher(None, a, b, autojunk=False).ratio()
                same_pairs.append(clean)
                changes += clean != SequenceMatcher(None, a, b).ratio()
            timed = [(turn, skeleton(note)) for turn, note in r.get("_baton_turns", [])
                     if note and turn < r["guess_turn"]]
            per_episode, early, late = [], [], []
            for (ta, a), (tb, b) in zip(timed, timed[1:]):
                if tb != ta + 1:
                    continue
                sim = SequenceMatcher(None, a, b, autojunk=False).ratio()
                per_episode.append(sim)
                if tb <= 7:
                    early.append(sim)
                if tb >= 13:
                    late.append(sim)
            actual_pairs += len(per_episode)
            if per_episode:
                episode_means.append(sum(per_episode) / len(per_episode))
            if base == "long" and early and late:
                trends.append(sum(late) / len(late) - sum(early) / len(early))
        if not same_pairs:
            continue
        row = {"same_pair_mean_noautojunk": sum(same_pairs) / len(same_pairs),
               "n_historical_pairs": len(same_pairs), "n_changed_pairs": changes,
               "actual_turn_pairs_without_terminal": actual_pairs,
               "n_episodes": len(episode_means),
               "episode_mean_without_terminal": (sum(episode_means) / len(episode_means)
                                                  if episode_means else None),
               "episode_mean_ci": t_ci(episode_means) if len(episode_means) >= 2 else None}
        if trends:
            row.update({"n_trend_episodes": len(trends),
                        "episode_trend_mean": sum(trends) / len(trends),
                        "episode_trend_ci": t_ci(trends),
                        "trend_pos": sum(d > 0 for d in trends),
                        "trend_neg": sum(d < 0 for d in trends),
                        "trend_ties": sum(d == 0 for d in trends)})
        out[f"{model}|{base}|{budget}"] = row
    return out


