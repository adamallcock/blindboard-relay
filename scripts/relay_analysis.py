def _contrast_side(key) -> str:
    """One side of a family contrast, named from its cell key."""
    _, cond, _, budget = key
    if budget == "full":
        return "visible"
    if budget == "retained":
        return "retained"
    name = _COND_NAME.get(cond, cond)
    return name if budget == "100" else f"{name} ($B{{=}}{budget}$)"


def _family_display(label: str, spec) -> tuple[str, str]:
    """(model, contrast) cells for a confirmatory-family row, derived from the
    declared cell keys rather than the free-text label: delta = b - a, so the
    contrast reads '<b> $-$ <a>'. A non-standard board and any parenthetical
    in the label (e.g. fresh seeds) become a trailing note."""
    if spec is None:  # unknown label: print it, typeset
        return "", label.replace(" - ", " $-$ ")
    key_a, key_b = spec
    notes = [_BASE_NAME.get(b, b) for b in dict.fromkeys((key_b[2], key_a[2])) if b != "std"]
    extra = re.search(r"\(([^)]*)\)\s*$", label)
    if extra:
        notes.append(re.sub(r"(\d)-(\d)", r"\1--\2", extra.group(1)))
    contrast = f"{_contrast_side(key_b)} $-$ {_contrast_side(key_a)}"
    if notes:
        contrast += f" ({'; '.join(notes)})"
    return _model_name(key_b[0]), contrast


