def load_cells(prompt_version: str = "relay-v2"):
    """(model, condition, base, budget) -> {seed: episode_result}.
    Refuses episodes whose result lacks the requested prompt_version stamp;
    returns (cells, refused_count). Later run dirs win per seed."""
    cells = defaultdict(dict)
    refused = 0
    for d in sorted(LLM.iterdir()):
        sp = d / "summary.json"
        if not sp.exists():
            continue
        s = json.loads(sp.read_text())
        base = "std"
        for tag in ("long", "numrow"):
            if f"-{tag}-" in d.name:
                base = tag
        for p in sorted(d.glob("seed*.json")):
            data = json.loads(p.read_text())
            r = data["result"]
            if r.get("prompt_version") != prompt_version:
                refused += 1
                continue
            r["_batons"] = [t.get("baton_out", "") for t in data.get("turns", [])]
            r["_baton_turns"] = [(t["turn"], t.get("baton_out", ""))
                                  for t in data.get("turns", [])]
            key = (SHORT.get(s["model"], s["model"]), s.get("condition", "freeform"),
                   base, str(s.get("budget")))
            cells[key][r["seed"]] = r
    return cells, refused


def sign_test_p(deltas):
    nz = [d for d in deltas if d != 0]
    if not nz:
        return 1.0
    k = sum(1 for d in nz if d > 0)
    n = len(nz)
    def binom(n, k):
        return math.comb(n, k) / 2 ** n
    tail = sum(binom(n, i) for i in range(min(k, n - k) + 1))
    return min(1.0, 2 * tail)


def bootstrap_ci(deltas, iters=10000, seed=7):
    rng = random.Random(seed)
    means = sorted(
        sum(rng.choice(deltas) for _ in deltas) / len(deltas) for _ in range(iters)
    )
    return means[int(0.025 * iters)], means[int(0.975 * iters)]


# Two-sided .975 t-quantiles by df (Abramowitz&Stegun); df>30 ~ normal.
_T975 = {1: 12.706, 2: 4.303, 3: 3.182, 4: 2.776, 5: 2.571, 6: 2.447, 7: 2.365,
         8: 2.306, 9: 2.262, 10: 2.228, 11: 2.201, 12: 2.179, 13: 2.160,
         14: 2.145, 15: 2.131, 16: 2.120, 17: 2.110, 18: 2.101, 19: 2.093,
         20: 2.086, 21: 2.080, 22: 2.074, 23: 2.069, 24: 2.064, 25: 2.060,
         26: 2.056, 27: 2.052, 28: 2.048, 29: 2.045, 30: 2.042}


def t_ci(deltas):
    """Paired-t 95% CI for the mean delta (the primary interval; neither
    parametric nor bootstrap coverage is guaranteed at n=10)."""
    n = len(deltas)
    if n < 2:
        return (float("nan"), float("nan"))
    m = sum(deltas) / n
    var = sum((d - m) ** 2 for d in deltas) / (n - 1)
    half = _T975.get(n - 1, 1.96) * math.sqrt(var / n)
    return (m - half, m + half)


def signed_rank_p(deltas):
    """Exact two-sided Wilcoxon signed-rank via full sign enumeration
    (midranks for ties; zeros dropped). Sensitivity check only — adds a
    symmetry assumption the sign test does not need. Exact up to n=16,
    normal approximation with tie correction beyond."""
    nz = [d for d in deltas if d != 0]
    n = len(nz)
    if n == 0:
        return 1.0
    mags = sorted((abs(d), i) for i, d in enumerate(nz))
    ranks = [0.0] * n
    i = 0
    while i < n:
        j = i
        while j + 1 < n and mags[j + 1][0] == mags[i][0]:
            j += 1
        r = (i + j) / 2 + 1
        for k in range(i, j + 1):
            ranks[mags[k][1]] = r
        i = j + 1
    w_pos = sum(r for r, d in zip(ranks, nz) if d > 0)
    if n <= 16:
        total = 0
        extreme = 0
        target = min(w_pos, sum(ranks) - w_pos)
        for mask in range(1 << n):
            w = sum(ranks[k] for k in range(n) if mask >> k & 1)
            total += 1
            if min(w, sum(ranks) - w) <= target + 1e-9:
                extreme += 1
        return extreme / total
    mean = sum(ranks) / 2
    var = sum(r * r for r in ranks) / 4
    if var == 0:
        return 1.0
    z = (w_pos - mean) / math.sqrt(var)
    p = math.erfc(abs(z) / math.sqrt(2))
    return min(1.0, p)


def bca_ci(deltas, iters=10000, seed=7):
    """BCa bootstrap CI (sensitivity interval alongside the paired-t)."""
    n = len(deltas)
    rng = random.Random(seed)
    obs = sum(deltas) / n
    boots = sorted(sum(rng.choice(deltas) for _ in range(n)) / n
                   for _ in range(iters))
    prop = sum(1 for b in boots if b < obs) / iters
    prop = min(max(prop, 1e-9), 1 - 1e-9)
    # inverse normal CDF (Acklam-lite via erfc inversion by bisection)
    def z_of(p_):
        lo_, hi_ = -8.0, 8.0
        for _ in range(80):
            mid = (lo_ + hi_) / 2
            if 0.5 * math.erfc(-mid / math.sqrt(2)) < p_:
                lo_ = mid
            else:
                hi_ = mid
        return (lo_ + hi_) / 2
    z0 = z_of(prop)
    jack = [(sum(deltas) - deltas[i]) / (n - 1) for i in range(n)]
    jm = sum(jack) / n
    num = sum((jm - j) ** 3 for j in jack)
    den = 6 * (sum((jm - j) ** 2 for j in jack) ** 1.5) or 1e-12
    a = num / den
    def pct(alpha):
        z = z_of(alpha)
        adj = 0.5 * math.erfc(-(z0 + (z0 + z) / (1 - a * (z0 + z))) / math.sqrt(2))
        idx = min(max(int(adj * iters), 0), iters - 1)
        return boots[idx]
    return pct(0.025), pct(0.975)


def holm_bh(rows, key="p_sign"):
    """Attach Holm and Benjamini-Hochberg adjusted p-values over the FULL
    row family (in place)."""
    m = len(rows)
    if not m:
        return
    by_p = sorted(range(m), key=lambda i: rows[i][key])
    # Holm step-down (adjusted p, monotone).
    running = 0.0
    for rank, i in enumerate(by_p):
        adj = (m - rank) * rows[i][key]
        running = max(running, min(1.0, adj))
        rows[i]["p_holm"] = running
    # BH step-up (adjusted p, monotone from the largest down).
    running = 1.0
    for rank in range(m - 1, -1, -1):
        i = by_p[rank]
        adj = m / (rank + 1) * rows[i][key]
        running = min(running, min(1.0, adj))
        rows[i]["p_bh"] = running


def paired_contrast(cell_a, cell_b):
    """Per-seed deltas (b - a) on shared seeds -> stats dict or None."""
    shared = sorted(set(cell_a) & set(cell_b))
    if len(shared) < 8:
        return None
    deltas = [cell_b[s]["board_accuracy"] - cell_a[s]["board_accuracy"] for s in shared]
    # Equal integer differences can have unequal float representations.
    board_sizes = {r["board_n"] for cell in (cell_a, cell_b)
                   for s, r in cell.items() if s in shared and "board_n" in r}
    if len(board_sizes) != 1:
        raise ValueError("paired board scores need one known board size")
    board_n = board_sizes.pop()

    def correct_keys(row):
        value = row.get("correct", round(row["board_accuracy"] * board_n))
        if (not isinstance(value, int)
                or abs(value / board_n - row["board_accuracy"]) > 1e-5):
            raise ValueError("board score does not match an integer correct-key count")
        return value

    key_deltas = [correct_keys(cell_b[s]) - correct_keys(cell_a[s]) for s in shared]
    return {"n": len(shared), "delta": sum(deltas) / len(deltas),
            "n_pos": sum(1 for d in deltas if d > 0),
            "n_neg": sum(1 for d in deltas if d < 0),
            "ci": t_ci(deltas), "ci_bca": bca_ci(deltas),
            "p_sign": sign_test_p(deltas), "p_wilcoxon": signed_rank_p(key_deltas)}


