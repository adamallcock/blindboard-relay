def write_drift_example():
    """One recorded v2 chain, with exact transmitted text and provenance."""
    path = LLM / "gpt-5.6-luna-medium-freeform-b100-20260714-180239/seed0000.json"
    data = json.loads(path.read_text())
    if data["result"].get("prompt_version") != "relay-v2":
        raise ValueError("drift example must be a main-v2 episode")
    replacements = {"\\": r"\textbackslash{}", "{": r"\{", "}": r"\}",
                    "$": r"\$", "&": r"\&", "%": r"\%", "#": r"\#",
                    "_": r"\_", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    lines = [GEN_HEADER, r"\begin{quote}\small\ttfamily\raggedright"]
    chosen = [t for t in data["turns"] if 4 <= t["turn"] <= 9]
    if [t["turn"] for t in chosen] != list(range(4, 10)):
        raise ValueError("drift example must contain six consecutive turns")
    for turn in chosen:
        note = turn["baton_out"]
        if len(note) > 100:
            raise ValueError("example must contain the transmitted prefix")
        escaped = "".join(replacements.get(c, c) for c in note)
        lines += [rf"\textnormal{{Turn {turn['turn']}:}} {escaped}\par\medskip"]
    lines += [r"\end{quote}"]
    (TABLES / "relay_drift_example.tex").write_text("\n".join(lines) + "\n")


