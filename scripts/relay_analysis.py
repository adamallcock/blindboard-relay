def between_chain_control(cells):
    """Cross-episode skeleton similarity at MATCHED generation (all chain
    pairs), early (gen<=6) vs late (gen>=12), long-base freeform cells.
    Chain-specific convention formation predicts within-chain stability
    rises while between-chain similarity does not. Control contributed by
    the external red-team review; adopted verbatim in spirit."""
    out = {}
    for (model, cond, base, budget), seeds in cells.items():
        if cond != "freeform" or base != "long":
            continue
        notes_by_chain = []
        for r in seeds.values():
            notes_by_chain.append([b for b in r.get("_batons", []) if b])
        buckets = {"early": [], "late": []}
        max_gen = max((len(n) for n in notes_by_chain), default=0)
        for g in range(max_gen):
            bucket = "early" if g <= 6 else "late" if g >= 12 else None
            if bucket is None:
                continue
            gen_notes = [c[g] for c in notes_by_chain if g < len(c)]
            for i in range(len(gen_notes)):
                for j in range(i + 1, len(gen_notes)):
                    buckets[bucket].append(SequenceMatcher(
                        None, skeleton(gen_notes[i]), skeleton(gen_notes[j])).ratio())
        if buckets["early"] and buckets["late"]:
            e = sum(buckets["early"]) / len(buckets["early"])
            l = sum(buckets["late"]) / len(buckets["late"])
            out[(model, budget)] = {"early": e, "late": l, "late_minus_early": l - e,
                                    "n_early": len(buckets["early"]),
                                    "n_late": len(buckets["late"])}
    return out


def pearson(xs, ys):
    n = len(xs)
    if n < 3:
        return None
    mx, my = sum(xs) / n, sum(ys) / n
    sx = math.sqrt(sum((x - mx) ** 2 for x in xs))
    sy = math.sqrt(sum((y - my) ** 2 for y in ys))
    if sx == 0 or sy == 0:
        return None
    return sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / (sx * sy)


def taxonomy(cells):
    out = {}
    plan_re = re.compile(r"\b(press|next|try|plan|probe|then|test|query|classify)\b", re.I)
    fact_re = re.compile(r"[=:]")
    for (model, cond, base, budget), seeds in cells.items():
        if cond != "freeform" or base != "std":
            continue
        counts = {"state": 0, "plan": 0, "mixed": 0, "neither": 0, "total": 0}
        for r in seeds.values():
            for b in r.get("_batons", []):
                if not b:
                    continue
                counts["total"] += 1
                has_fact, has_plan = bool(fact_re.search(b)), bool(plan_re.search(b))
                key = ("mixed" if has_fact and has_plan else
                       "state" if has_fact else "plan" if has_plan else "neither")
                counts[key] += 1
        if counts["total"]:
            out[(model, budget)] = counts
    return out



def _collection_date(dirname: str) -> str | None:
    """YYYY-MM-DD from a run directory's -YYYYMMDD-HHMMSS stamp."""
    m = re.search(r"-(20\d{6})-\d{6}$", dirname)
    return f"{m.group(1)[:4]}-{m.group(1)[4:6]}-{m.group(1)[6:]}" if m else None


