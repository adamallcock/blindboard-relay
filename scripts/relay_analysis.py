def _dated_episode_cost(data: dict, model: str, dirname: str) -> float | None:
    """Sum price_call over each call's own usage, at the list price in effect
    on the collection date. Relay episodes keep per-call usage in
    turns[].replies[]; transcript controls keep it on assistant messages.
    None when per-call usage is missing or any call is unpriceable."""
    on = _collection_date(dirname)
    if on is None:
        return None
    calls = [rep.get("usage") for turn in data.get("turns", [])
             for rep in turn.get("replies", [])]
    calls += [m.get("usage") for m in data.get("transcript", [])
              if m.get("role") == "assistant"]
    calls = [u for u in calls if u]
    if not calls:
        return None
    total = 0.0
    for u in calls:
        c = price_call(_pricing_key(model), u, on=on)
        if c is None:
            return None
        total += c
    return total

def census_and_cost():
    """Corpus counts and list-price cost over ALL stored relay artifacts
    (any prompt version — collection cost is collection cost)."""
    episodes = 0
    notes_total = 0
    cost_by_model = defaultdict(float)
    for root in (LLM, SVG):
        if not root.exists():
            continue
        for d in sorted(root.iterdir()):
            if not d.is_dir():
                continue
            for p in d.glob("seed*.json"):
                data = json.loads(p.read_text())
                r = data["result"]
                episodes += 1
                notes_total += sum(
                    1 for t in data.get("turns", []) if t.get("baton_out"))
                usage = r.get("usage") or {}
                model = r.get("model") or ""
                if r.get("cost_usd_list") is not None:
                    cost_by_model[model] += float(r["cost_usd_list"])
                    continue
                dated = _dated_episode_cost(data, model, d.name)
                if dated is not None:
                    cost_by_model[model] += dated
                    continue
                prices = (PRICES.get(model) or PRICES.get(f"gemini/{model}")
                          or PRICES.get(f"anthropic/{model}"))
                if prices and usage:
                    cost_by_model[model] += (
                        usage.get("input_tokens", 0) / 1e6 * prices[0]
                        + usage.get("output_tokens", 0) / 1e6 * prices[1])
    # Failed attempts are billed for the calls they completed; relay_run
    # records that spend per seed (summary.json, or failed_run.json when a
    # whole cell failed). No episode file exists for them, so add it here.
    for root in (LLM, SVG):
        if not root.exists():
            continue
        for d in sorted(root.iterdir()):
            for name in ("summary.json", "failed_run.json"):
                fp = d / name
                if fp.exists():
                    rec = json.loads(fp.read_text())
                    for cost in (rec.get("failed_cost_usd_list") or {}).values():
                        cost_by_model[rec.get("model") or ""] += float(cost)
    # Probe rows (svg transcription probe): probe.json = {"rows": [...]}.
    # Probe usage is folded into the dir-level adapter totals at collection
    # time and is not itemized per row; the row count is the census datum.
    probe_pairs = 0
    for pj in SVG.glob("*/probe.json") if SVG.exists() else []:
        try:
            entries = json.loads(pj.read_text())
        except Exception:
            continue
        rows = entries.get("rows") if isinstance(entries, dict) else entries
        if isinstance(rows, list):
            probe_pairs += len(rows)
    return {"episodes_stored": episodes, "notes_stored": notes_total,
            "probe_pairs": probe_pairs,
            "cost_by_model": dict(cost_by_model),
            "cost_total": sum(cost_by_model.values())}



