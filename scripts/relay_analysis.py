def terra_excess(cells):
    """Terra-minus-nano externalization cost: per seed, (visible - note) for
    each model, averaged over the four budgets both share, paired over the
    seeds every one of those cells holds. Descriptive, outside any family."""
    budgets = ("200", "100", "75", "50")
    keys = [(m, "freeform", "std", b) for m in ("terra", "nano") for b in budgets + ("full",)]
    if not all(cells.get(k) for k in keys):
        return None
    shared = sorted(set.intersection(*(set(cells[k]) for k in keys)))
    if len(shared) < 8:
        return None

    def acc(m, b, s):
        return cells[(m, "freeform", "std", b)][s]["board_accuracy"]

    diffs = [sum((acc("terra", "full", s) - acc("terra", b, s))
                 - (acc("nano", "full", s) - acc("nano", b, s)) for b in budgets) / len(budgets)
             for s in shared]
    return {"n": len(diffs), "delta": sum(diffs) / len(diffs), "ci": t_ci(diffs),
            "p_sign": sign_test_p(diffs)}


